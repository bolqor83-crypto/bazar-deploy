#!/usr/bin/env node
/**
 * VLM-проверка Промта 15 — вспомогательный сигнал, НЕ gate
 * (критерий приёмки — golden pixelmatch + чек-лист, ADR 0014/0015).
 *
 * 8 ключевых кадров чек-листа с публичного URL. Вопросы — про
 * КОНКРЕТНЫЕ дефекты новых элементов: сетка 2/3, StockDot,
 * компактная карточка, группы заказов, цветные иконки, меню
 * сортировки. Общие «впечатления» не запрашиваются.
 *
 * Запуск: node scripts/визор-15.mjs (кадры уже сняты в
 * download/промт15/чек-лист).
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const SRC = path.resolve('download/промт15/чек-лист');
const OUT_DIR = path.resolve('download/промт15/vlm');
fs.mkdirSync(OUT_DIR, { recursive: true });

/** Кадр → специфичный контекст вопроса. */
const FRAMES = {
  'catalog-light-390.png':
    'Каталог покупателя: адаптивная сетка из 2 колонок, компактные карточки ~275px (фото 1:1, название 2 строки, цена), точка наличия 12px в левом верхнем углу фото, кнопка сортировки в заголовке секции.',
  'catalog-dark-768.png':
    'Каталог в тёмной теме на широком экране 768px: сетка из 3 колонок (планшет/широкий web), компактные карточки, точки наличия на фото.',
  'catalog-sort-open-light-390.png':
    'Каталог с открытым меню сортировки: компактная кнопка сортировки в заголовке секции, выпадающий список вариантов.',
  'orders-grouped-light-390.png':
    'Список заказов покупателя, сгруппированный по продавцам: заголовок группы (аватар с инициалами, имя продавца, строка «N заказов · сумма», чип «N активных», шеврон), под ним карточки заказов.',
  'orders-collapsed-light-390.png':
    'Список заказов по продавцам, первая группа свёрнута: виден только заголовок группы с шевроном вниз.',
  'seller-orders-grouped-light-390.png':
    'Заказы оптовика, сгруппированные по покупателям: заголовки групп с аватарами-инициалами, суммами и чипами активных заказов.',
  'tools-more-light-390.png':
    'Экран «Все инструменты» с цветными иконками инструментов (заказы, доставка, склад, аналитика, финансы, товары) в группах.',
  'context-sheet-dark-390.png':
    'Шит переключения контекста в тёмной теме: цветные иконки ролей (покупатель — зелёный, оптовик — золотой, перевозчик — синий, владелец точки — бежевый).',
};

const PROMPT = (
  ctx,
) => `Перед тобой кадр мобильного приложения Bazar (оптовый аграрный рынок). Контекст кадра: ${ctx}

Найди ТОЛЬКО конкретные визуальные ДЕФЕКТЫ:
1. текст, который не читается (слишком бледный, мелкий, наложение)
2. обрезанные элементы (кнопка, текст, фото выходят за границы)
3. съехавшие отступы (элемент прижат к краю, налезает на соседний)
4. наложения элементов друг на друга
5. сломанное выравнивание сетки/колонок
6. точки наличия или иконки, сливающиеся с фоном до нечитаемости

Если дефектов нет — напиши ровно: "дефектов нет".
Не давай оценок, впечатлений и рекомендаций. Только список дефектов
с указанием места на экране, по-русски, максимум 3 пункта.`;

async function main() {
  for (const [frame, ctx] of Object.entries(FRAMES)) {
    const inFile = path.join(SRC, frame);
    const outFile = path.join(OUT_DIR, `${frame.replace('.png', '')}.json`);
    if (!fs.existsSync(inFile)) {
      console.log(`нет кадра: ${frame}`);
      continue;
    }
    if (fs.existsSync(outFile)) {
      const cached = JSON.parse(fs.readFileSync(outFile, 'utf-8'));
      console.log(`\n=== ${frame} (кэш) ===`);
      console.log(cached.choices[0].message.content);
      continue;
    }
    try {
      execFileSync(
        'z-ai',
        ['vision', '-p', PROMPT(ctx), '-i', inFile, '-o', outFile],
        { stdio: 'pipe', timeout: 120_000 },
      );
      const verdict = JSON.parse(fs.readFileSync(outFile, 'utf-8'));
      console.log(`\n=== ${frame} ===`);
      console.log(verdict.choices[0].message.content);
      // Мягкий pacing: пауза между вызовами VLM (урок 429 из 12).
      await new Promise((r) => setTimeout(r, 4000));
    } catch (error) {
      console.log(`\n=== ${frame}: ошибка ${error.message?.slice(0, 120)} ===`);
    }
  }
}

main();
